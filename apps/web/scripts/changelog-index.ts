// Writes src/lib/changelog-entries/index.ts: one import per entry file, newest first. The index is not committed, so two
// pull requests that each add an entry file never conflict. next.config.ts, vitest.config.ts and playwright.config.ts call
// this, so every dev server, build, typecheck (next typegen), unit run and e2e run sees the current entries.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** An entry file is named after its `at` in Vietnam time (2026-11-16T16:30:00+07:00 is 20261116-163000.ts), so the names sort by time and no two entries can share one. */
export const ENTRY_FILE = /^\d{8}-\d{6}\.ts$/;

export const ENTRIES_DIR = fileURLToPath(new URL('../src/lib/changelog-entries/', import.meta.url));

/** The index text for these entry file names. */
export function changelogIndex(names: string[]): string {
  const files = names.filter((n) => ENTRY_FILE.test(n)).sort().reverse();
  return [
    '// Generated by scripts/changelog-index.ts from the entry files in this folder. Do not edit or commit it.',
    ...files.map((n, i) => `import e${i} from './${n.slice(0, -3)}';`),
    '',
    `export const ENTRIES = [${files.map((_, i) => `e${i}`).join(', ')}];`,
    '',
  ].join('\n');
}

/** Writes the index when it is missing or out of date; an unchanged index is left alone, so a running dev server does not reload. */
export function writeChangelogIndex(dir = ENTRIES_DIR): void {
  const text = changelogIndex(readdirSync(dir));
  const file = `${dir}index.ts`;
  let old = '';
  try {
    old = readFileSync(file, 'utf8');
  } catch {
    // No index yet.
  }
  if (old !== text) writeFileSync(file, text);
}
