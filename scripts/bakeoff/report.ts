// Bake-off report (plan B.6 step 4): recomputes every number in docs/BAKEOFF.md from the job log, the blind maps and the scores.
//   tsx scripts/bakeoff/report.ts --maps <dir with blind-map-<set>.json> [--root dir] [--out docs/BAKEOFF.md]
// Reads <root>/out/jobs.jsonl, <root>/blind/<set>/scores-<set>.csv for half-1, half-2 and extra when present, and the second judging in
// <root>/blind/rejudge/scores-rejudge.csv, whose ids are clip ids from the halves.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseArgs } from 'node:util';
import { defaultRoot, isMain } from './common.ts';
import { parseCsv } from './judge.ts';
import { keyId, latest, lineSpend, readLines, spend, type JobLine, type SetName } from './jobs.ts';
import type { ClipMap } from './anonymise.ts';

export const PASS_BAR = 0.7;

/** Wilson score interval at 95%; [0, 0] for n = 0. */
export function wilson(k: number, n: number, z = 1.96): [number, number] {
  if (!n) return [0, 0];
  const p = k / n;
  const d = 1 + (z * z) / n;
  const c = (p + (z * z) / (2 * n)) / d;
  const h = (z * Math.sqrt((p * (1 - p)) / n + (z * z) / (4 * n * n))) / d;
  return [Math.max(0, c - h), Math.min(1, c + h)];
}

export interface Verdict { id: string; set: SetName; model: string; image: number; pass: boolean; faults: string[] }

export interface ReportData {
  lines: JobLine[];
  verdicts: Verdict[];
  /** Second judging of a few clips: clip id -> pass. */
  rejudge: Record<string, boolean>;
  /** Render seconds the provider reported, by provider job id (out/provider-times.json); missing ids show as "-". */
  providerSec?: Record<string, number>;
  /** What each provider billed, read off its usage page (out/billed.json); the ledger books these, not the cap-guard counts. */
  billed?: Record<string, { usd: number; source: string }>;
}

const pct = (x: number): string => `${Math.round(x * 100)}%`;
const usd = (x: number): string => `$${x.toFixed(2)}`;

export function buildReport({ lines, verdicts: judged0, rejudge, providerSec = {}, billed = {} }: ReportData): string {
  const last = latest(lines);
  const bakeoff = [...last.values()].filter((l) => l.round === 'bakeoff');
  // A clip the provider refused or failed to render is a fail for that model; a key that never reached the provider (our side) is left
  // out of the rate and listed instead.
  const verdicts = [...judged0, ...bakeoff.filter((l) => l.status === 'failed').map((l): Verdict => ({
    id: '-', set: (l.set ?? 'half-1') as SetName, model: l.model, image: l.image, pass: false, faults: ['render'],
  }))];
  const missing = bakeoff.filter((l) => !['succeeded', 'failed'].includes(l.status));
  const models = [...new Set(verdicts.map((v) => v.model))].sort();
  const rows = models.map((model) => {
    const vs = verdicts.filter((v) => v.model === model);
    const k = vs.filter((v) => v.pass).length;
    const [lo, hi] = wilson(k, vs.length);
    const jobs = vs.map((v) => last.get(keyId({ image: v.image, model, round: 'bakeoff' }))).filter((l): l is JobLine => !!l);
    const cost = jobs.reduce((a, l) => a + lineSpend(l), 0) / (jobs.length || 1);
    const faults: Record<string, number> = {};
    for (const f of vs.flatMap((v) => v.faults)) faults[f] = (faults[f] ?? 0) + 1;
    return { model, n: vs.length, k, rate: vs.length ? k / vs.length : 0, lo, hi, cost, faults };
  });
  const passing = rows.filter((r) => r.rate >= PASS_BAR).sort((a, b) => b.rate - a.rate || a.cost - b.cost);

  const times = verdicts.map((v) => {
    const all = lines.filter((l) => keyId(l) === keyId({ image: v.image, model: v.model, round: 'bakeoff' }));
    const sub = all.find((l) => l.status === 'submitted');
    const done = all.find((l) => l.status === 'succeeded');
    const sec = sub?.providerJobId ? providerSec[sub.providerJobId] : undefined;
    return { ...v, min: sub && done ? (Date.parse(done.at) - Date.parse(sub.at)) / 60_000 : NaN, sec };
  });
  const judged = Object.keys(rejudge);
  const agree = judged.filter((id) => verdicts.find((v) => v.id === id)?.pass === rejudge[id]).length;
  const total = spend(lines);

  const out = [
    '# Bake-off result',
    '',
    'Generated by `scripts/bakeoff/report.ts`; do not edit the numbers by hand.',
    '',
    `## Pass rate (bar ${pct(PASS_BAR)})`,
    '',
    '| Model | Passed | Rate | Wilson 95% | Cost per clip | Faults |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows.map((r) => `| ${r.model} | ${r.k}/${r.n} | ${pct(r.rate)} | ${pct(r.lo)}–${pct(r.hi)} | ${usd(r.cost)} | ${Object.entries(r.faults).map(([f, c]) => `${f} ${c}`).join(', ') || 'none'} |`),
    '',
    '## Decision',
    '',
    passing.length
      ? `**Go.** Enable ${passing.map((r) => r.model).join(' and ')}; the picker pre-selects ${passing[0]!.model} (higher rate, the cheaper one on a tie).`
      : `**No-go.** Neither model reaches ${pct(PASS_BAR)}.`,
    '',
    missing.length
      ? `Left out of the rates, never rendered for reasons on our side: ${missing.map((l) => `image ${l.image} ${l.model} (${l.status}${l.error ? `: ${l.error}` : ''})`).join('; ')}.`
      : 'Every planned clip rendered or failed at the provider.',
    '',
    '## Second judging',
    '',
    judged.length ? `${agree}/${judged.length} clips got the same pass or fail from a second, fresh judge (${judged.join(', ')}).` : 'Not run.',
    '',
    '## Spend',
    '',
    `Counted against the spend stop ${usd(total.total)} (${Object.entries(total.byProvider).map(([p, s]) => `${p} ${usd(s)}`).join(', ')}), counting the canary, every bake-off clip and any other logged job, each at the larger of estimate and reported cost.`,
    '',
    ...(Object.keys(billed).length
      ? [
          `Billed $${Object.values(billed).reduce((a, b) => a + b.usd, 0).toFixed(2)} (${Object.entries(billed).map(([p, b]) => `${p} ${usd(b.usd)}`).join(', ')}), as the providers' usage pages show; the ledger books these amounts.`,
          '',
          ...Object.entries(billed).map(([p, b]) => `- ${p}: ${b.source}`),
          '',
        ]
      : []),
    '## Clips',
    '',
    'Render seconds are what the provider reported; minutes run from the provider accepting the job to the clip saved on this PC, so they include any download delay.',
    '',
    '| Set | Image | Model | Pass | Faults | Render s | Minutes |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...times.sort((a, b) => a.image - b.image || a.model.localeCompare(b.model))
      .map((t) => `| ${t.set} | ${t.image} | ${t.model} | ${t.pass ? 'yes' : 'no'} | ${t.faults.join(', ') || '-'} | ${t.sec === undefined ? '-' : Math.round(t.sec)} | ${Number.isNaN(t.min) ? '-' : t.min.toFixed(1)} |`),
    '',
  ];
  return out.join('\n');
}

function readScores(file: string): Map<string, { pass: boolean; faults: string[] }> {
  const [, ...rows] = parseCsv(readFileSync(file, 'utf8'));
  return new Map(rows.map(([id, pass, faults]) => [id!, { pass: pass === 'true', faults: faults ? faults.split(';') : [] }]));
}

export function loadReportData(root: string, maps: string): ReportData {
  const verdicts: Verdict[] = [];
  for (const set of ['half-1', 'half-2', 'extra'] as SetName[]) {
    const scores = join(root, 'blind', set, `scores-${set}.csv`);
    if (!existsSync(scores)) continue;
    const map = JSON.parse(readFileSync(join(maps, `blind-map-${set}.json`), 'utf8')) as ClipMap;
    for (const [id, s] of readScores(scores)) {
      const c = map.clips[id];
      if (!c) throw new Error(`${set}: ${id} is not in the map`);
      verdicts.push({ id, set, model: c.model, image: c.image, ...s });
    }
  }
  const rj = join(root, 'blind', 'rejudge', 'scores-rejudge.csv');
  const rejudge = existsSync(rj) ? Object.fromEntries([...readScores(rj)].map(([id, s]) => [id, s.pass])) : {};
  const pt = join(root, 'out', 'provider-times.json');
  const providerSec = existsSync(pt) ? (JSON.parse(readFileSync(pt, 'utf8')) as Record<string, number>) : {};
  const bf = join(root, 'out', 'billed.json');
  const billed = existsSync(bf) ? (JSON.parse(readFileSync(bf, 'utf8')) as ReportData['billed']) : {};
  return { lines: readLines(join(root, 'out')), verdicts, rejudge, providerSec, billed };
}

if (isMain(import.meta.url)) {
  const { values } = parseArgs({ options: { maps: { type: 'string' }, root: { type: 'string' }, out: { type: 'string' } } });
  if (!values.maps) throw new Error('--maps is required');
  const md = buildReport(loadReportData(values.root ?? defaultRoot(), values.maps));
  writeFileSync(values.out ?? join('docs', 'BAKEOFF.md'), md);
  console.log(md);
}
